/**
 * Returns a localized copy of an Article based on the requested Language.
 */
export function getLocalizedArticle(article: Article, language: string): Article {
  if (language !== 'hi') {
    return article;
  }

  const hiData = ARTICLES_HINDI_DATA[article.id];
  if (!hiData) {
    return article;
  }

  return {
    ...article,
    title: hiData.title,
    subtitle: hiData.subtitle,
    summary: hiData.summary,
    keyTakeaways: hiData.keyTakeaways,
    sections: hiData.sections,
    checklist: hiData.checklist,
    redFlags: hiData.redFlags,
    homeCareTips: hiData.homeCareTips,
    targetAudience: hiData.targetAudience,
    dietaryNotes: hiData.dietaryNotes || article.dietaryNotes,
    medicalReviewer: {
      ...article.medicalReviewer,
      role: hiData.reviewerRole || article.medicalReviewer.role,
      institution: hiData.reviewerInstitution || article.medicalReviewer.institution,
    },
  };
}

/**
 * Returns an array of localized articles.
 */
export function getLocalizedArticles(articles: Article[], language: string): Article[] {
  return articles.map((a) => getLocalizedArticle(a, language));
}
